document.getElementById('cutter-form').addEventListener('submit', async (e) => {
    e.preventDefault();
    const t = translations[currentLang];
    
    const url = urlInput.value;
    const startTime = startTimeInput.value;
    const endTime = endTimeInput.value;
    
    const btn = document.getElementById('submit-btn');
    const statusDiv = document.getElementById('status-message');
    
    btn.classList.add('btn-loading');
    btn.disabled = true;
    statusDiv.classList.add('hidden');
    statusDiv.className = '';
    
    try {
        let payload;
        if (currentPlatform === 'tiktok') {
            const mode = document.querySelector('input[name="tkMode"]:checked').value;
            payload = { url, platform: 'tiktok', mode, startTime, endTime };
        } else {
            payload = { url, startTime, endTime, platform: 'youtube' };
        }
            
        const response = await fetch('/api/process', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(payload)
        });
        
        const data = await response.json();
        
        if (response.ok) {
            statusDiv.textContent = t.success;
            statusDiv.classList.add('success');
            
            if(data.downloadUrl) {
                // Yönlendirme ile indir (Tarayıcı pop-up engelleyicisini aşmak için)
                window.location.href = data.downloadUrl;
            }
        } else {
            throw new Error(data.error || t.errorGeneral);
        }
    } catch (err) {
        statusDiv.textContent = err.message;
        statusDiv.classList.add('error');
    } finally {
        btn.classList.remove('btn-loading');
        btn.disabled = false;
        statusDiv.classList.remove('hidden');
    }
});
